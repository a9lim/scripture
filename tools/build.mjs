#!/usr/bin/env node
// Stages the deploy tree in dist/ and the Worker's bundled corpus in .build/.
//
//   dist/    the app (index.html, 404.html, main.js, colors.js, styles.css,
//            src/), the corpus (data/, text/), the vendored shared layer
//            (shared/), static/ copied to the root, and generated sitemap.xml,
//            robots.txt, and opensearch.xml
//   .build/  corpus.generated.mjs: works.json order plus every manifest
//
// about.md's title, description, and updated date are written into the
// staged index.html and main.js, and %ORIGIN% in the staged HTML is replaced
// with ORIGIN from site.config.mjs. Source files are never modified.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ORIGIN } from '../site.config.mjs';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DIST = join(ROOT, 'dist');
const BUILD = join(ROOT, '.build');

const read = rel => readFileSync(join(ROOT, rel), 'utf8');
const readJSON = rel => JSON.parse(read(rel));
const emit = (rel, text) => writeFileSync(join(DIST, rel), text);
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const noDotfiles = src => !src.split('/').pop().startsWith('.');

// --- about.md frontmatter ---

const aboutSrc = read('about.md');
const fm = aboutSrc.match(/^---\n([\s\S]*?)\n---\n/);
if (!fm) throw new Error('about.md: missing frontmatter');
const about = Object.fromEntries(fm[1].split('\n').map(line => {
  const i = line.indexOf(':');
  return [line.slice(0, i).trim(), line.slice(i + 1).trim()];
}));
for (const key of ['title', 'description', 'updated']) {
  if (!about[key]) throw new Error(`about.md: missing ${key}`);
}
if (!/^\d{4}-\d{2}-\d{2}$/.test(about.updated)) throw new Error('about.md: updated must be YYYY-MM-DD');

// --- stage ---

rmSync(DIST, { recursive: true, force: true });
mkdirSync(DIST, { recursive: true });
for (const dir of ['src', 'data', 'text', 'shared']) {
  cpSync(join(ROOT, dir), join(DIST, dir), { recursive: true, filter: noDotfiles });
}
cpSync(join(ROOT, 'static'), DIST, { recursive: true, filter: noDotfiles });
for (const file of ['colors.js', 'styles.css']) cpSync(join(ROOT, file), join(DIST, file));

function replaceOnce(text, re, replacement, label) {
  if (!re.test(text)) throw new Error(`${label}: pattern ${re} not found`);
  return text.replace(re, replacement);
}

let html = read('index.html');
html = replaceOnce(html, /<title>[^<]*<\/title>/, `<title>${esc(about.title)}</title>`, 'index.html title');
for (const attr of ['name="description"', 'property="og:description"', 'name="twitter:description"']) {
  html = replaceOnce(html, new RegExp(`(<meta ${attr} content=")[^"]*(")`), `$1${esc(about.description)}$2`, `index.html ${attr}`);
}
for (const attr of ['property="og:title"', 'name="twitter:title"']) {
  html = replaceOnce(html, new RegExp(`(<meta ${attr} content=")[^"]*(")`), `$1${esc(about.title)}$2`, `index.html ${attr}`);
}
html = replaceOnce(html, /("description"\s*:\s*)"[^"]*"/, `$1${JSON.stringify(about.description)}`, 'index.html JSON-LD description');
html = replaceOnce(html, /("dateModified"\s*:\s*)"[^"]*"/, `$1${JSON.stringify(about.updated)}`, 'index.html JSON-LD dateModified');
emit('index.html', html.replaceAll('%ORIGIN%', ORIGIN));
emit('404.html', read('404.html').replaceAll('%ORIGIN%', ORIGIN));

const main = replaceOnce(read('main.js'), /(lastUpdated\s*:\s*['"])[^'"]+(['"])/, `$1${about.updated}$2`, 'main.js lastUpdated');
emit('main.js', main);

// --- corpus module for the Worker ---

const works = readJSON('data/works.json');
const manifests = Object.fromEntries(works.map(id => [id, readJSON(`data/${id}/manifest.json`)]));
for (const [id, m] of Object.entries(manifests)) {
  if (m.id !== id) throw new Error(`data/${id}/manifest.json: id is ${m.id}`);
}
mkdirSync(BUILD, { recursive: true });
writeFileSync(join(BUILD, 'corpus.generated.mjs'), [
  '// GENERATED by tools/build.mjs from data/ — do not hand-edit.',
  `export const WORKS = ${JSON.stringify(works)};`,
  `export const MANIFESTS = ${JSON.stringify(manifests)};`,
  '',
].join('\n'));

// --- sitemap, robots, OpenSearch ---

function gitLastmod(rel) {
  try {
    const iso = execFileSync('git', ['log', '-1', '--format=%aI', '--', rel], { cwd: ROOT, encoding: 'utf8' }).trim();
    return iso ? iso.slice(0, 10) : about.updated;
  } catch { return about.updated; }
}

const urls = [{ loc: `${ORIGIN}/`, lastmod: about.updated, changefreq: 'monthly', priority: '1.0' }];
for (const id of works) {
  const lastmod = gitLastmod(`data/${id}/manifest.json`);
  urls.push({ loc: `${ORIGIN}/${id}`, lastmod, changefreq: 'monthly', priority: '0.8' });
  for (const book of manifests[id].books) {
    const start = book.start ?? 1;
    for (let i = 0; i < book.chapters; i++) {
      urls.push({ loc: `${ORIGIN}/${id}/${book.id}-${start + i}`, lastmod, changefreq: 'yearly', priority: '0.6' });
    }
  }
}
emit('sitemap.xml', [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...urls.map(u => `  <url>\n    <loc>${u.loc}</loc>\n    <lastmod>${u.lastmod}</lastmod>\n    <changefreq>${u.changefreq}</changefreq>\n    <priority>${u.priority}</priority>\n  </url>`),
  '</urlset>',
  '',
].join('\n'));

emit('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${ORIGIN}/sitemap.xml\n`);

emit('opensearch.xml', `<?xml version="1.0" encoding="UTF-8"?>
<OpenSearchDescription xmlns="http://a9.com/-/spec/opensearch/1.1/">
  <ShortName>Scripture</ShortName>
  <LongName>Scripture — search sixteen sacred texts</LongName>
  <Description>Full-text search across sixteen sacred texts, including the King James Bible, the Quran (Pickthall), the Book of Mormon, and the Tao Te Ching.</Description>
  <Image width="16" height="16" type="image/x-icon">${ORIGIN}/favicon.ico</Image>
  <Url type="text/html" template="${ORIGIN}/?q={searchTerms}"/>
  <Language>en</Language>
  <InputEncoding>UTF-8</InputEncoding>
  <OutputEncoding>UTF-8</OutputEncoding>
</OpenSearchDescription>
`);

console.log(`dist/: staged for ${ORIGIN}; sitemap.xml has ${urls.length} URLs`);
